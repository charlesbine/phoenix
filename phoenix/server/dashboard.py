    if static_dir.exists():
        app.mount("/static/assets", StaticFiles(directory=str(static_dir)), name="assets")

    # Serve the compiled Vue dashboard. Source lives in frontend/; production
    # assets are generated by `bun run build` and intentionally not committed.
    frontend_assets_dir = phoenix_paths.FRONTEND_DIST_DIR / "assets"
    if frontend_assets_dir.exists():
        app.mount("/assets", StaticFiles(directory=str(frontend_assets_dir)), name="frontend-assets")

