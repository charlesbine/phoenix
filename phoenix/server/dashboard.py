    def _frontend_index_response() -> FileResponse | HTMLResponse:
        index_file = phoenix_paths.FRONTEND_DIST_DIR / "index.html"
        if index_file.exists():
            return FileResponse(index_file)
        return _missing_frontend_response()

    def _frontend_public_file(path: str) -> FileResponse | None:
        if "/" in path or "\\" in path:
            return None
        candidate = phoenix_paths.FRONTEND_DIST_DIR / path
        if candidate.is_file() and candidate.name != "index.html":
            return FileResponse(candidate)
        return None

    def _reserved_frontend_path(path: str) -> bool:
        reserved = ("api", "assets", "data", "proxy", "static", "ws")
        return any(path == prefix or path.startswith(f"{prefix}/") for prefix in reserved)

    @app.get("/", response_class=HTMLResponse)
    async def index():
        return _frontend_index_response()

    @app.get("/{path:path}", response_class=HTMLResponse)
    async def frontend_spa(path: str):
        if _reserved_frontend_path(path):
            raise HTTPException(status_code=404)
        if public_file := _frontend_public_file(path):
            return public_file
        return _frontend_index_response()

    return app
