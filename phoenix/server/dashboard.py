    def _check_health() -> dict:
        """Shared health check logic."""
        import os
        from phoenix.paths import PACKAGE_DIR

        result: dict = {"status": "ok", "issues": []}

        if publisher is not None:
            player = get_device_db().get(settings.node_device)
            player_name = player["name"] if player else settings.node_device
            player_status = publisher.sync_status
            result["player"] = {"name": player_name, "status": player_status}
            if player_status == "offline":
                result["issues"].append(f"{player_name} player offline")
                result["status"] = "degraded"
        elif settings.platform == "serial":
            m4_connected = os.path.exists(settings.serial_port)
            result["m4"] = {"connected": m4_connected, "port": settings.serial_port}
            if not m4_connected:
                result["issues"].append(f"M4 not available on {settings.serial_port}")
                result["status"] = "degraded"

        # MQTT
        result["mqtt"] = {"connected": mqtt_client.connected, "broker": settings.mqtt_broker or None}
        if settings.mqtt_broker and not mqtt_client.connected:
            result["issues"].append("MQTT disconnected")
            result["status"] = "degraded"

        # Memory
        try:
            with open("/proc/meminfo") as f:
                mem = {}
                for line in f:
                    parts = line.split(":")
                    if len(parts) >= 2:
                        mem[parts[0].strip()] = int(parts[1].strip().split()[0])
                total = mem.get("MemTotal", 0) // 1024
                avail = mem.get("MemAvailable", 0) // 1024
                result["memory"] = {"total_mb": total, "available_mb": avail, "used_pct": round((total - avail) / total * 100) if total else 0}
                if avail < 100:
                    result["issues"].append(f"Low memory: {avail}MB available")
                    result["status"] = "degraded"
        except Exception:
            pass

        # Load
        try:
            load1, load5, load15 = os.getloadavg()
            result["load"] = {"1m": round(load1, 2), "5m": round(load5, 2), "15m": round(load15, 2)}
        except OSError:
            pass

        # Uptime
        try:
            with open("/proc/uptime") as f:
                uptime_secs = float(f.read().split()[0])
                hours = int(uptime_secs // 3600)
                mins = int((uptime_secs % 3600) // 60)
                result["uptime"] = f"{hours}h {mins}m"
        except Exception:
            pass

        # Last render times
        log_file = PACKAGE_DIR / "logs" / "phoenix.log"
        render_times: dict[str, float] = {}
        if log_file.exists():
            for line in log_file.read_text(errors="replace").splitlines()[-500:]:
                if "Render complete" in line:
                    try:
                        name = line.split("[")[2].split("]")[0]
                        time_str = line.split("(")[1].split("s")[0]
                        render_times[name] = float(time_str)
                    except (IndexError, ValueError):
                        pass
        result["render_times"] = render_times

        # App / panel data-ingress health (for enabled or panel-rotated active apps)
        svc = get_svc()
        device_enabled = get_device_db().enabled_app_names()
        unhealthy_apps = []
        for app_obj in svc.list_apps():
            if not app_obj.active or (not app_obj.enabled and app_obj.name not in device_enabled):
                continue
            if app_obj.health_status == "unhealthy":
                unhealthy_apps.append({
                    "name": app_obj.name,
                    "reason": app_obj.health_reason,
                    "last_healthy": app_obj.last_healthy.isoformat() if app_obj.last_healthy else None,
                    "last_healthy_human": (
                        humanize.naturaltime(datetime.now() - app_obj.last_healthy)
                        if app_obj.last_healthy
                        else "never"
                    ),
                    "skip_when_unhealthy": app_obj.skip_when_unhealthy,
                    "skipped_unhealthy": app_obj.is_skipped_unhealthy,
                })
        result["unhealthy_apps"] = unhealthy_apps
        if unhealthy_apps:
            result["status"] = "degraded"

        return result

