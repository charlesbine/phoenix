        import time
        with _connect() as conn:
            rows = conn.execute(
                "SELECT url, fetched_at, ttl, length(body) as size FROM http_cache ORDER BY fetched_at DESC"
            ).fetchall()
            now = time.time()
            return [
                {
                    "url": r["url"],
                    "age_seconds": round(now - r["fetched_at"]),
                    "ttl": r["ttl"],
                    "fresh": (now - r["fetched_at"]) < r["ttl"],
                    "size_bytes": r["size"],
                }
                for r in rows
            ]

