    @app.websocket("/ws/state")
    async def ws_state(ws: WebSocket):
        """Push {apps, config, now_playing} on connect and whenever it changes,
        with a heartbeat every ~15s. One socket replaces per-client polling.
        Pass ?device=<id> to scope the push to a single panel."""
        await ws.accept()
        device = ws.query_params.get("device") or None
        last_sig: str | None = None
        ticks = 0
        try:
            while True:
                svc = get_svc()
                if device:
                    apps = _device_apps(device)
                    config = _device_config(device) or {
                        "layout_mode": "cycle", "cycle_interval": 10, "brightness": 128,
                    }
                else:
                    cfg = svc.get_display_config()
                    apps = [_serialize_app(a) for a in svc.list_apps()]
                    config = {
                        "layout_mode": cfg.layout_mode,
                        "cycle_interval": cfg.cycle_interval,
                        "brightness": cfg.brightness,
                    }
                current = _read_now_playing(device)
                payload = {
                    "apps": apps,
                    "config": config,
                    "now_playing": current,
                    "now_playing_is_live": _is_live_app_name(current),
                }
                if publisher and device == settings.node_device:
                    payload["node_sync"] = publisher.sync_status
                # change detection ignores the humanized/volatile timestamps
                sig = json.dumps(
                    {
                        "a": [
                            {
                                k: v
                                for k, v in a.items()
                                if k not in ("last_updated", "last_updated_human", "last_healthy_human", "health_checked_at")
                            }
                            for a in apps
                        ],
                        "c": payload["config"],
                        "n": payload["now_playing"],
                        "node_sync": payload.get("node_sync"),
                    },
                    default=str,
                    sort_keys=True,
                )
                ticks += 1
                if sig != last_sig or ticks >= 15:
                    await ws.send_json(payload)
                    last_sig = sig
                    ticks = 0
                await asyncio.sleep(1.0)
        except WebSocketDisconnect:
            pass
        except Exception:
            pass

